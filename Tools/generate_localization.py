#!/usr/bin/env python3
"""Validate Localization/*.json and generate Sources/L10nCatalog.swift.

Usage:
    python3 Tools/generate_localization.py            # validate + write catalog
    python3 Tools/generate_localization.py --check    # validate only

Every language must contain exactly the same keys as Localization/en.json and
must keep the same printf placeholders (%d, %@, ...) and newline count.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALIZATION_DIR = ROOT / "Localization"
OUTPUT = ROOT / "Sources" / "L10nCatalog.swift"
SOURCE_LANGUAGE = "en"
# Order matters: it is the order shown in the settings picker and in the README
# language bar. The Swift enum owns the canonical order; this list only drives
# which JSON files are compiled into the catalog.
LANGUAGES = ["en", "zh-Hans", "zh-Hant", "ja", "ko", "es", "fr", "de"]

STRICT = "--strict" in sys.argv

PLACEHOLDER_RE = re.compile(r"%(?:\d+\$)?[-+0 #']*(?:\d+|\*)?(?:\.(?:\d+|\*))?[hlLqjzt]*[diouxXeEfFgGaAcspn@%]")


def swift_identifier(language: str) -> str:
    return "table_" + re.sub(r"[^A-Za-z0-9]", "_", language)


def swift_literal(value: str) -> str:
    out = []
    for char in value:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def placeholders(value: str) -> list[str]:
    return sorted(match.group(0) for match in PLACEHOLDER_RE.finditer(value))


def main() -> int:
    master_path = LOCALIZATION_DIR / f"{SOURCE_LANGUAGE}.json"
    master = json.loads(master_path.read_text(encoding="utf-8"))
    master_keys = list(master.keys())

    tables: dict[str, dict[str, str]] = {}
    errors: list[str] = []

    for language in LANGUAGES:
        path = LOCALIZATION_DIR / f"{language}.json"
        if not path.exists():
            if STRICT:
                errors.append(f"missing file: {path.relative_to(ROOT)}")
            else:
                print(f"warning: skipping missing {path.relative_to(ROOT)}", file=sys.stderr)
            continue
        table = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(table, dict):
            errors.append(f"{path.name}: root must be an object")
            continue

        missing = [key for key in master_keys if key not in table]
        extra = [key for key in table if key not in master]
        if missing:
            errors.append(f"{path.name}: missing {len(missing)} keys: {', '.join(missing[:8])}")
        if extra:
            errors.append(f"{path.name}: {len(extra)} unknown keys: {', '.join(extra[:8])}")

        for key in master_keys:
            if key not in table:
                continue
            value = table[key]
            if not isinstance(value, str) or not value.strip():
                errors.append(f"{path.name}: empty or non-string value for {key}")
                continue
            if placeholders(value) != placeholders(master[key]):
                errors.append(
                    f"{path.name}: placeholder mismatch for {key}: "
                    f"expected {placeholders(master[key])}, got {placeholders(value)}"
                )
            if value.count("\n") != master[key].count("\n"):
                errors.append(f"{path.name}: newline mismatch for {key}")

        tables[language] = {key: table[key] for key in master_keys if key in table}

    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        return 1

    if "--check" in sys.argv:
        print(f"ok: {len(tables)} languages, {len(master_keys)} keys")
        return 0

    lines = [
        "// Generated by Tools/generate_localization.py from Localization/*.json.",
        "// Do not edit this file by hand; edit the JSON files and re-run the script.",
        "",
        "enum L10nCatalog {",
        "    static let tables: [String: [String: String]] = [",
    ]
    available = [language for language in LANGUAGES if language in tables]
    for language in available:
        lines.append(f'        "{language}": {swift_identifier(language)},')
    lines.append("    ]")

    for language in available:
        lines.append("")
        lines.append(f"    private static let {swift_identifier(language)}: [String: String] = [")
        for key in master_keys:
            value = tables[language][key]
            lines.append(f"        {swift_literal(key)}: {swift_literal(value)},")
        lines.append("    ]")

    lines.append("}")
    lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(available)} languages, {len(master_keys)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
